export const TECHNOLOGY_CATEGORIES = Array.from(
  new Set(TECHNOLOGIES.map((t) => t.category)),
) as Technology['category'][];

/** Free-text search across name + aka, for the inventory picker. */
export function searchTechnologies(query: string): Technology[] {
  const q = query.trim().toLowerCase();
  if (!q) return TECHNOLOGIES;
  return TECHNOLOGIES.filter((t) => {
    if (t.name.toLowerCase().includes(q)) return true;
    if (t.slug.includes(q)) return true;
    return (t.aka ?? []).some((a) => a.toLowerCase().includes(q));
  });
}
